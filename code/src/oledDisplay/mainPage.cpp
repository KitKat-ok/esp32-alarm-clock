auto formatTemperature = [](float minTemp, float maxTemp)
{
    char tempStr[6];
    float avgTemp = (minTemp + maxTemp) / 2.0;
    dtostrf(avgTemp, 4, 1, tempStr);
    return String(tempStr) + "C";
};

